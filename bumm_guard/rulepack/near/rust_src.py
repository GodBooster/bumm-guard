"""Tiny Rust-source helper shared by the NEAR detectors.

This is deliberately *not* a Rust parser. It provides just enough structure
for the rules:

* ``mask_source``: blank out comments and string/char literal contents while
  keeping every offset and newline, so brace matching and regexes cannot be
  fooled by ``"{"`` or ``// fn foo()``.
* ``match_close``: brace/paren/bracket matching on masked text.
* attribute collection on items (``#[private]``, ``#[near]`` ...), both forward
  (inside an impl body) and backward (before an ``impl`` keyword).
* ``impl`` block detection (exported ``#[near]`` / ``#[near_bindgen]`` impls,
  trait impls) and method extraction inside them.

Known limits: no macro expansion, no ``include!``, no type information,
methods generated by macros are invisible.
"""

from __future__ import annotations

import bisect
import re
from dataclasses import dataclass, field
from pathlib import Path


# --------------------------------------------------------------------------
# masking
# --------------------------------------------------------------------------

def _blank(s: str) -> str:
    """Replace every char except newlines with a space."""
    return "".join(c if c == "\n" else " " for c in s)


def mask_source(src: str) -> str:
    """Return ``src`` with comments and literal contents replaced by spaces.

    Length and newlines are preserved, so offsets/line numbers map 1:1 to the
    original. String quotes are kept (contents blanked); char literals likewise;
    lifetimes (``'a``) are left alone.
    """
    out: list[str] = []
    i, n = 0, len(src)
    while i < n:
        c = src[i]
        nxt = src[i + 1] if i + 1 < n else ""
        if c == "/" and nxt == "/":
            j = src.find("\n", i)
            j = n if j < 0 else j
            out.append(" " * (j - i))
            i = j
        elif c == "/" and nxt == "*":
            depth, j = 1, i + 2
            while j < n and depth:
                if src.startswith("/*", j):
                    depth += 1
                    j += 2
                elif src.startswith("*/", j):
                    depth -= 1
                    j += 2
                else:
                    j += 1
            out.append(_blank(src[i:j]))
            i = j
        elif c in "rb" and _raw_string_at(src, i):
            end = _raw_string_end(src, i)
            out.append(src[i:end][0] + _blank(src[i + 1:end]))
            i = end
        elif c == '"':
            j = i + 1
            while j < n and src[j] != '"':
                j += 2 if src[j] == "\\" else 1
            j = min(j, n - 1)
            out.append('"' + _blank(src[i + 1:j]) + '"')
            i = j + 1
        elif c == "'":
            j = _char_literal_end(src, i)
            if j is None:
                out.append(c)
                i += 1
            else:
                out.append("'" + _blank(src[i + 1:j]) + "'")
                i = j + 1
        else:
            out.append(c)
            i += 1
    return "".join(out)


_RAW_RE = re.compile(r'(?:br|r)(#*)"')


def _raw_string_at(src: str, i: int) -> bool:
    if i > 0 and (src[i - 1].isalnum() or src[i - 1] == "_"):
        return False
    return _RAW_RE.match(src, i) is not None


def _raw_string_end(src: str, i: int) -> int:
    m = _RAW_RE.match(src, i)
    assert m
    closing = '"' + m.group(1)
    j = src.find(closing, m.end())
    return len(src) if j < 0 else j + len(closing)


def _char_literal_end(src: str, i: int) -> int | None:
    """Index of the closing quote if ``src[i]`` opens a char literal."""
    n = len(src)
    if i + 1 >= n:
        return None
    if src[i + 1] == "\\":
        j = src.find("'", i + 3)  # '\'' needs the escaped quote skipped
        return None if j < 0 or j - i > 12 else j
    if i + 2 < n and src[i + 2] == "'" and src[i + 1] != "'":
        return i + 2
    return None


# --------------------------------------------------------------------------
# matching helpers
# --------------------------------------------------------------------------

def match_close(s: str, i: int, o: str = "{", c: str = "}") -> int:
    """Index of the bracket closing the one at ``s[i]`` (``-1`` if unbalanced).

    ``s`` must be masked (see ``mask_source``).
    """
    depth = 0
    for j in range(i, len(s)):
        ch = s[j]
        if ch == o:
            depth += 1
        elif ch == c:
            depth -= 1
            if depth == 0:
                return j
    return -1


def match_open_backward(s: str, i: int, o: str, c: str) -> int:
    """Index of the opener matching the closer at ``s[i]`` (``-1`` if none)."""
    depth = 0
    for j in range(i, -1, -1):
        ch = s[j]
        if ch == c:
            depth += 1
        elif ch == o:
            depth -= 1
            if depth == 0:
                return j
    return -1


def strip_angles(text: str) -> str:
    """Remove ``<...>`` groups (generics), ignoring ``->`` arrows."""
    out, depth = [], 0
    for k, ch in enumerate(text):
        if ch == "<":
            depth += 1
        elif ch == ">" and not (k > 0 and text[k - 1] == "-"):
            depth = max(0, depth - 1)
        elif depth == 0:
            out.append(ch)
    return "".join(out)


def enclosing_calls(code: str, pos: int) -> list[str]:
    """Names of the calls/macros whose ``(...)`` argument list encloses ``pos``.

    Innermost first. ``require!(a == b, ..)`` yields ``["require!"]`` for a
    position inside the parentheses.
    """
    names: list[str] = []
    depth = 0
    for j in range(pos - 1, -1, -1):
        ch = code[j]
        if ch == ")":
            depth += 1
        elif ch == "(":
            if depth == 0:
                m = re.search(r"([A-Za-z_][\w:]*!?)\s*$", code[max(0, j - 80):j])
                names.append(m.group(1) if m else "")
            else:
                depth -= 1
    return names


# --------------------------------------------------------------------------
# attributes
# --------------------------------------------------------------------------

@dataclass(frozen=True)
class Attr:
    path: str   # e.g. "near_sdk::private"
    args: str   # text inside the outer parentheses, "" if none
    text: str   # full "#[...]" text
    pos: int

    @property
    def name(self) -> str:
        """Last path segment: ``near_sdk::private`` -> ``private``."""
        return self.path.split("::")[-1]


_ATTR_HEAD = re.compile(r"#!?\[\s*([A-Za-z_][\w:]*)")


def _make_attr(code: str, start: int, end: int) -> Attr | None:
    text = code[start:end + 1]
    m = _ATTR_HEAD.match(text)
    if not m:
        return None
    rest = text[m.end():].lstrip()
    args = ""
    if rest.startswith("("):
        close = match_close(rest, 0, "(", ")")
        args = rest[1:close] if close > 0 else ""
    return Attr(m.group(1), args, text, start)


def attrs_forward(code: str, pos: int) -> tuple[list[Attr], int]:
    """Collect consecutive attributes starting at ``pos`` (after whitespace).

    Returns ``(attrs, position of the first non-attribute token)``.
    """
    attrs: list[Attr] = []
    n = len(code)
    while True:
        while pos < n and code[pos].isspace():
            pos += 1
        if pos < n and code[pos] == "#":
            k = pos + 1
            if k < n and code[k] == "!":
                k += 1
            while k < n and code[k].isspace():
                k += 1
            if k < n and code[k] == "[":
                end = match_close(code, k, "[", "]")
                if end < 0:
                    break
                a = _make_attr(code, pos, end)
                if a:
                    attrs.append(a)
                pos = end + 1
                continue
        break
    return attrs, pos


def attrs_before(code: str, pos: int) -> list[Attr]:
    """Attributes stacked directly above the item that starts at ``pos``."""
    found: list[Attr] = []
    i = pos
    while True:
        j = i
        while j > 0 and code[j - 1].isspace():
            j -= 1
        if j > 0 and code[j - 1] == "]":
            op = match_open_backward(code, j - 1, "[", "]")
            if op > 0:
                h = op - 1
                while h > 0 and code[h].isspace():
                    h -= 1
                if code[h] == "!":
                    h -= 1
                if code[h] == "#":
                    a = _make_attr(code, h, j - 1)
                    if a:
                        found.append(a)
                    i = h
                    continue
        break
    found.reverse()
    return found


# --------------------------------------------------------------------------
# cfg(test) removal
# --------------------------------------------------------------------------

_CFG_TEST = re.compile(r"#\[\s*cfg\s*\(\s*(?:all\s*\(\s*)?test\b[^\]]*\]")


def blank_cfg_test(code: str) -> str:
    """Blank every item annotated ``#[cfg(test)]`` (mods, fns, impls)."""
    while True:
        m = _CFG_TEST.search(code)
        if not m:
            return code
        _, pos = attrs_forward(code, m.end())
        j, depth = pos, 0
        while j < len(code):
            ch = code[j]
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif depth <= 0 and ch in "{;":
                break
            j += 1
        if j < len(code) and code[j] == "{":
            j = match_close(code, j)
            j = len(code) - 1 if j < 0 else j
        code = code[:m.start()] + _blank(code[m.start():j + 1]) + code[j + 1:]


# --------------------------------------------------------------------------
# impls and methods
# --------------------------------------------------------------------------

EXPORT_ATTRS = ("near", "near_bindgen")


@dataclass
class Impl:
    attrs: list[Attr]
    header: str
    self_type: str
    is_trait: bool
    exported: bool
    start: int          # position of `impl` keyword
    body_start: int     # position of `{`
    body_end: int       # position of matching `}`


@dataclass
class Method:
    file: "SourceFile"
    impl: Impl
    name: str
    attrs: list[Attr]
    is_pub: bool
    receiver: str | None      # "ref" (&self), "mut" (&mut self), "value" or None
    params: str               # text between the parentheses
    item_start: int           # first attribute (or `pub`/`fn`)
    name_pos: int
    body_start: int | None    # position of `{`; None for declarations
    body_end: int | None

    @property
    def line(self) -> int:
        return self.file.line_of(self.name_pos)

    @property
    def body(self) -> str:
        if self.body_start is None:
            return ""
        return self.file.code[self.body_start:self.body_end + 1]

    @property
    def has_body(self) -> bool:
        return self.body_start is not None

    def has_attr(self, name: str) -> bool:
        return any(a.name == name for a in self.attrs)

    @property
    def is_entry(self) -> bool:
        """Callable from outside via the NEAR runtime."""
        return self.impl.exported and (self.is_pub or self.impl.is_trait)

    def param_attr_names(self) -> list[str]:
        return [m.group(1).split("::")[-1] for m in re.finditer(r"#\[\s*([\w:]+)", self.params)]


_IMPL_KW = re.compile(r"\bimpl\b")
_FN_HEAD = re.compile(
    r"^(?P<vis>pub(?:\s*\([^)]*\))?\s+)?(?:(?:const|async|unsafe|default)\s+)*fn\s+(?P<name>[A-Za-z_]\w*)"
)
_RECEIVER = re.compile(
    r"^\s*(?:#\[[^\]]*\]\s*)*(?:(?P<ref>&\s*(?:'\w+\s*)?(?P<mut>mut\s+)?self\b)|(?:mut\s+)?(?P<val>self\b))"
)


def _find_impls(code: str) -> list[Impl]:
    impls: list[Impl] = []
    for m in _IMPL_KW.finditer(code):
        pre = re.search(r"((?:pub(?:\s*\([^)]*\))?\s+)?(?:unsafe\s+)?)$", code[max(0, m.start() - 40):m.start()])
        start = m.start() - (len(pre.group(1)) if pre else 0)
        k = start
        while k > 0 and code[k - 1].isspace():
            k -= 1
        if k > 0 and code[k - 1] not in "};]{":
            continue  # `-> impl Trait`, `x: impl Trait` ...
        j = m.end()
        while j < len(code) and code[j] not in "{;":
            j += 1
        if j >= len(code) or code[j] == ";":
            continue
        end = match_close(code, j)
        if end < 0:
            continue
        header = code[m.end():j]
        bare = strip_angles(header)
        fm = re.search(r"\bfor\b", bare)
        is_trait = fm is not None
        target = bare[fm.end():] if fm else bare
        tm = re.search(r"[A-Za-z_]\w*", target.replace("&", " "))
        attrs = attrs_before(code, start)
        exported = any(
            a.name == "near_bindgen"
            or (a.name == "near" and "contract_state" not in a.args and "serializers" not in a.args)
            for a in attrs
        )
        impls.append(Impl(attrs, header.strip(), tm.group(0) if tm else "", is_trait, exported, m.start(), j, end))
    return impls


def _methods_of(file: "SourceFile", impl: Impl) -> list[Method]:
    code = file.code
    methods: list[Method] = []
    pos, end = impl.body_start + 1, impl.body_end
    while pos < end:
        attrs, pos = attrs_forward(code, pos)
        if pos >= end:
            break
        item_start = attrs[0].pos if attrs else pos
        j, depth = pos, 0
        while j < end:
            ch = code[j]
            if ch in "([":
                depth += 1
            elif ch in ")]":
                depth -= 1
            elif depth <= 0 and ch in "{;":
                break
            j += 1
        header = code[pos:j]
        fm = _FN_HEAD.match(header)
        has_brace = j < end and code[j] == "{"
        close = match_close(code, j) if has_brace else j
        if close < 0:
            break
        if fm:
            popen = code.find("(", pos + fm.end("name"), j if j > pos else end)
            params, receiver = "", None
            if popen >= 0:
                pclose = match_close(code, popen, "(", ")")
                if pclose > 0:
                    params = code[popen + 1:pclose]
                    rm = _RECEIVER.match(params)
                    if rm:
                        receiver = ("mut" if rm.group("mut") else "ref") if rm.group("ref") else "value"
            vis = fm.group("vis")
            is_pub = bool(vis) and "(" not in vis
            methods.append(Method(
                file, impl, fm.group("name"), attrs, is_pub, receiver, params,
                item_start, pos + fm.start("name"),
                j if has_brace else None, close if has_brace else None,
            ))
        pos = close + 1
        if has_brace and not fm:
            while pos < end and code[pos].isspace():
                pos += 1
            if pos < end and code[pos] == ";":
                pos += 1
    return methods


# --------------------------------------------------------------------------
# source file
# --------------------------------------------------------------------------

@dataclass
class SourceFile:
    path: str                   # path as displayed to the user
    raw: str
    code: str = field(repr=False, default="")
    impls: list[Impl] = field(default_factory=list, repr=False)
    methods: list[Method] = field(default_factory=list, repr=False)

    def __post_init__(self) -> None:
        self.code = blank_cfg_test(mask_source(self.raw))
        self._starts = [0] + [m.end() for m in re.finditer(r"\n", self.code)]
        self.impls = _find_impls(self.code)
        self.methods = [m for im in self.impls for m in _methods_of(self, im)]

    @classmethod
    def from_path(cls, path: str | Path, display: str | None = None) -> "SourceFile":
        text = Path(path).read_text(encoding="utf-8", errors="replace")
        return cls(display or str(path), text)

    def line_of(self, pos: int) -> int:
        return bisect.bisect_right(self._starts, pos)

    def line_text(self, line: int) -> str:
        lines = self.raw.splitlines()
        return lines[line - 1].strip() if 0 < line <= len(lines) else ""

    def leading_comments(self, pos: int) -> str:
        """Raw text of the contiguous comment/attribute lines directly above ``pos``."""
        line = self.line_of(pos) - 1
        lines = self.raw.splitlines()
        out: list[str] = []
        while line >= 1:
            t = lines[line - 1].strip()
            if t.startswith("//") or t.startswith("#[") or t.startswith("*") or t.startswith("/*"):
                out.append(t)
                line -= 1
            else:
                break
        return "\n".join(out)
